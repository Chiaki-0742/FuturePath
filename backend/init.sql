-- 11.9 有没有一条步骤都没配的案例（应该 0 条）
SELECT COUNT(*) AS 无步骤案例数
FROM `cases` c LEFT JOIN `case_steps` s ON s.case_id = c.id
WHERE s.id IS NULL;

-- 11.10 一条完整的案例看长什么样（含步骤）
SELECT c.title, s.phase, s.content, s.is_key
FROM `cases` c
JOIN `case_steps` s ON s.case_id = c.id
WHERE c.id = 1
ORDER BY s.order_no;


