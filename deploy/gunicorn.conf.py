# ==============================================================
#  gunicorn 配置（上线时后端用什么跑）
#
#  本地开发用 `python run.py` 就行，那个是 Flask 自带的开发服务器：
#  单线程、会泄漏调试信息、并发一高就卡。上线必须换成 gunicorn。
#
#  启动方式（在 backend 目录下）：
#      venv/bin/gunicorn -c ../deploy/gunicorn.conf.py run:app
#  或者让宝塔的「Python项目管理器」把启动命令填成：
#      gunicorn -c deploy/gunicorn.conf.py run:app
#  （run.py 里已经有 `app = create_app()`，所以入口写 run:app）
# ==============================================================

bind = "127.0.0.1:5000"     # 只监听本机，外网一律走 Nginx 转发
                            # 千万不要写 0.0.0.0 —— 那样 Flask 就直接暴露在公网了

# --------------------------------------------------------------
#  ⚠️ workers 必须是 1，这一条是硬性的，别改成 2、4
#
#  原因：后端的登录 token 和"找回密码"凭证都存在【进程内存】里
#  （backend/app/routes/auth.py 的 TOKENS / RESET_TOKENS 两个字典）。
#  gunicorn 开多个 worker = 起了好几个互不相通的 Python 进程，
#  在 A 进程登录拿到的 token，请求被分到 B 进程时就查不到 → 用户会
#  "时好时坏地掉登录"，而且极难排查。
#
#  想在单 worker 下扛并发，靠下面的 threads（同一进程内的多线程共享内存），
#  这比多进程安全得多。等以后真要做大，再把 token 换成 Redis 或数据库表，
#  那时候才能上多 worker。
# --------------------------------------------------------------
workers = 1
worker_class = "gthread"
threads = 8

# --------------------------------------------------------------
#  超时：默认 30 秒会把 AI 问答掐断
#
#  对话接口要等大模型回答，实测 4~6 秒，但网络抖动或模型排队时会更久；
#  前端那边单独把超时放宽到了 55 秒。如果后端 30 秒就先把连接断了，
#  用户看到的是"服务器内部错误"，而前端还在傻等 —— 两边要一致。
#  这里给 75 秒，留足余量（也大于前端的 55 秒）。
# --------------------------------------------------------------
timeout = 75
graceful_timeout = 30
keepalive = 5

# 故意【不设】max_requests（"跑满 N 个请求就自动重启进程"）：
# 那个设置一重启，内存里的 token 就全没了，所有人都得重新登录。
# 等以后 token 搬进 Redis/数据库再加。

accesslog = "-"      # 访问日志打到标准输出，宝塔的项目日志里能看到
errorlog = "-"
loglevel = "info"

proc_name = "futurepath"
