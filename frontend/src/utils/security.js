/**
 * 密保问题的「可选清单」与答案规则。
 *
 * 为什么问题要由我们给定、而不是让用户随便写：
 *   1. 用户自己写的问题，十有八九是"我的生日""我的手机号"
 *      —— 这些恰恰是别人最容易查到的，等于没设；
 *   2. 后端是按题目原文存进 users.security_question 的，
 *      统一的清单也方便以后做统计和文案。
 *
 * 挑问题的标准：答案对本人来说一辈子不会变、但对别人来说猜不到。
 * 所以「你最喜欢的明星」这种就不合格（会变），「你的学号」也不合格
 * （同班同学都能查到）。
 */
export const SECURITY_QUESTIONS = [
  '你小学班主任的名字',
  '你小学的校名',
  '你最好的朋友的名字',
  '你童年最喜欢的动画片',
  '你家的第一只宠物叫什么',
  '你最喜欢的一门课',
]

/**
 * 答案规则 —— 必须和后端 auth.py 里的常量保持一致：
 *   SECURITY_ANSWER_MIN = 2，SECURITY_ANSWER_MAX = 64
 * 前端松、后端紧的话，用户会"填完了提交才被打回来"。
 */
export const ANSWER_MIN = 2
export const ANSWER_MAX = 64

/**
 * 把答案归一化后再比对（后端存的和比的都是归一化之后的值）。
 *
 * 为什么需要它：用户设置时写「毛毛」，找回时打成「毛毛 」「Maomao」，
 * 严格比对会让他觉得"我明明答对了却说我错"，然后扭头去注册新账号。
 * 三步：去首尾空白 → 中间连续空白压成一个 → 转小写。
 * 中文不受大小写影响，这一步主要是照顾英文和数字答案。
 */
export function normalizeAnswer(raw) {
  return String(raw ?? '')
    .split(/\s+/)
    .filter(Boolean)
    .join(' ')
    .toLowerCase()
}
